
"""Validate CricketIQ's engineered feature datasets.
Checks feature completeness, chronological separation, and
basic point-in-time correctness before model training.
"""

import pandas as pd
from Config import PROCESSED_DIR

DATA_DIR = PROCESSED_DIR / "ml"

SPLIT_FILES = {
    "train": "kohli_train_features.csv",
    "validation": "kohli_validation_features.csv",
    "test": "kohli_test_features.csv",
}

EXPECTED_ROWS = {
    "train": 6236,
    "validation": 466,
    "test": 425,
}


def load_feature_splits() -> dict[str, pd.DataFrame]: # Load the three datasets generated by feature engineering.
    datasets = {}
    for split_name, filename in SPLIT_FILES.items():
        file_path = DATA_DIR / filename
        if not file_path.is_file():
            raise FileNotFoundError(f"Missing file: {file_path}")
        datasets[split_name] = pd.read_csv(file_path)
    return datasets

def validate_splits(datasets: dict[str, pd.DataFrame]) -> None:  # Verify row counts, identifiers, and season boundaries.
    all_delivery_ids = []
    for name, data in datasets.items():
        assert len(data) == EXPECTED_ROWS[name], (
            f"Unexpected number of rows in {name}"
        )
        assert not data["delivery_id"].duplicated().any(), (
            f"Duplicate delivery IDs in {name}"
        )
        assert not data.isna().any().any(), (
            f"Missing values found in {name}"
        )
        if name == "train":
            assert data["season"].max() <= 2024
        elif name == "validation":
            assert data["season"].eq(2025).all()
        else:
            assert data["season"].eq(2026).all()

        all_delivery_ids.extend(data["delivery_id"].tolist())
        print(f"{name.title()}: PASSED")

    assert len(all_delivery_ids) == len(set(all_delivery_ids)), (
        "Delivery IDs overlap between splits."
    )

def validate_historical_features(
    datasets: dict[str, pd.DataFrame],
) -> None:  # Check the initial values of historical features.

    combined = pd.concat(
        datasets.values(),
        ignore_index=True,
    )

    combined["match_date"] = pd.to_datetime(
        combined["match_date"],
        errors="raise",
    )

    delivery_sequence = pd.to_numeric(
        combined["delivery_id"].str.rsplit("|", n=1).str[-1],
        errors="raise",
    )
    combined["_delivery_sequence"] = delivery_sequence
    combined = combined.sort_values(
        [
            "match_date",
            "match_id",
            "innings",
            "over",
            "_delivery_sequence",
        ]
    )

    first_innings_deliveries = combined.groupby(
        ["match_id", "innings"]
    ).head(1)
    assert (
        first_innings_deliveries["innings_runs_before"] == 0
    ).all(), "First delivery contains prior innings runs."
    assert (
        first_innings_deliveries["innings_balls_before"] == 0
    ).all(), "First delivery contains prior innings balls."
    assert combined["matchup_balls_before"].ge(0).all()
    assert combined["career_balls_before"].ge(0).all()
    assert combined["recent_10_boundary_rate"].between(
        0, 1
    ).all()
    print("Historical feature checks Pass")


def main() -> None: # Execute the feature-quality audit.
    datasets = load_feature_splits()
    validate_splits(datasets)
    validate_historical_features(datasets)


if __name__ == "__main__":
    main()
